-- Biblioteca reutilizable de logos para las plantillas de documentos.
-- Los binarios viven en el bucket privado sbss-documentos; PostgreSQL guarda
-- únicamente sus metadatos y la referencia al objeto.
CREATE TABLE IF NOT EXISTS public.logos_documentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(200) NOT NULL,
  ruta_archivo VARCHAR(100) NOT NULL UNIQUE,
  mime_type VARCHAR(40) NOT NULL CHECK (mime_type IN ('image/png', 'image/jpeg')),
  tamano_bytes INTEGER NOT NULL CHECK (tamano_bytes > 0 AND tamano_bytes <= 2097152),
  creado_por_usuario_id INTEGER NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_logos_documentos_nombre
  ON public.logos_documentos(nombre, id DESC);

ALTER TABLE public.logos_documentos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.logos_documentos FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.logos_documentos_id_seq FROM anon, authenticated;
