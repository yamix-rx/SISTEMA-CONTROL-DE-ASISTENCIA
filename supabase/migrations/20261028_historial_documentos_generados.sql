-- Historial privado e inmutable de PDF generados desde el módulo Documentos.
-- No confundir con documentos_empleado: estos últimos se entregan y revisan.
CREATE TABLE IF NOT EXISTS public.documentos_generados (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL REFERENCES public.empleados(id) ON DELETE RESTRICT,
  empresa_id INTEGER NOT NULL REFERENCES public.empresas(id) ON DELETE RESTRICT,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  tipo_codigo VARCHAR(50) NOT NULL,
  tipo_nombre VARCHAR(150) NOT NULL,
  nombre_archivo VARCHAR(200) NOT NULL,
  ruta_archivo VARCHAR(100) NOT NULL UNIQUE,
  fecha_emision DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_documentos_generados_fecha
  ON public.documentos_generados(created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_documentos_generados_empleado
  ON public.documentos_generados(empleado_id,created_at DESC);

ALTER TABLE public.documentos_generados ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.documentos_generados FROM anon,authenticated;
