-- SBSS · Esquema inicial para Supabase PostgreSQL
-- Derivado de backend/base-actualizada.sql (rama main, 2026-10-26).
-- No importar datos de demostración. Ejecutar SOLO en un proyecto nuevo.
-- Acceso a las tablas reservado al servidor; la API de Supabase no tiene políticas públicas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  descripcion VARCHAR(255) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.empresas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  razon_social VARCHAR(150) NOT NULL,
  ruc VARCHAR(11) NULL,
  direccion VARCHAR(255) NULL,
  telefono VARCHAR(20) NULL,
  email_contacto VARCHAR(120) NULL,
  logo_url VARCHAR(255) NULL,
  logo_data BYTEA NULL,
  logo_iv BYTEA NULL,
  logo_tag BYTEA NULL,
  logo_mime VARCHAR(50) NULL,
  estado VARCHAR(20) CHECK (estado IN ('activo', 'inactivo')) DEFAULT 'activo',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.areas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  empresa_id INTEGER NOT NULL,
  FOREIGN KEY (empresa_id) REFERENCES empresas(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.cargos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  area_id INTEGER NOT NULL,
  FOREIGN KEY (area_id) REFERENCES areas(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.empleados (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_documento VARCHAR(20) CHECK (tipo_documento IN ('DNI', 'CE', 'PASAPORTE')) DEFAULT 'DNI',
  numero_documento VARCHAR(15) NULL UNIQUE,
  nombres VARCHAR(100) NOT NULL,
  apellidos VARCHAR(100) NOT NULL,
  foto_perfil VARCHAR(255) NULL,
  fecha_nacimiento DATE NULL,
  telefono VARCHAR(20) NULL,
  correo_personal VARCHAR(120) NULL,
  direccion VARCHAR(255) NULL,
  carrera VARCHAR(100) NULL,
  institucion_educativa VARCHAR(150) NULL,
  empresa_id INTEGER NOT NULL,
  area_id INTEGER NOT NULL,
  cargo_id INTEGER NOT NULL,
  puesto VARCHAR(150) NULL,
  tipo_vinculo VARCHAR(50) NOT NULL DEFAULT 'trabajador',
  horas_totales_asignadas DECIMAL(8,2) NULL DEFAULT 0.00,
  horas_completadas DECIMAL(6,2) NULL DEFAULT 0.00,
  estado VARCHAR(20) CHECK (estado IN ('activo', 'inactivo', 'finalizado', 'suspendido')) DEFAULT 'activo',
  fecha_ingreso DATE NOT NULL,
  fecha_finalizacion DATE NULL,
  observaciones_rrhh TEXT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (empresa_id) REFERENCES empresas(id),
  FOREIGN KEY (area_id) REFERENCES areas(id),
  FOREIGN KEY (cargo_id) REFERENCES cargos(id)
);

CREATE TABLE IF NOT EXISTS public.usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL UNIQUE,
  rol_id INTEGER NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  sesion_version INTEGER NOT NULL DEFAULT 0,
  debe_cambiar_clave BOOLEAN NOT NULL DEFAULT FALSE,
  activo BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE,
  FOREIGN KEY (rol_id) REFERENCES roles(id)
);

CREATE TABLE IF NOT EXISTS public.practicante_detalles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL UNIQUE,
  horas_meta DECIMAL(8,2) NOT NULL DEFAULT 320,
  fecha_vencimiento_convenio DATE NULL,
  estado_completado BOOLEAN DEFAULT FALSE,
  fecha_completado DATE NULL,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.horarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL,
  dia_semana SMALLINT NOT NULL,
  turno VARCHAR(20) CHECK (turno IN ('manana', 'tarde', 'completo')) DEFAULT 'manana',
  hora_entrada TIME NOT NULL,
  hora_salida TIME NOT NULL,
  tolerancia_minutos INTEGER NULL DEFAULT 0,
  activo BOOLEAN DEFAULT TRUE,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE,
  CONSTRAINT uk_empleado_dia UNIQUE (empleado_id, dia_semana)
);

CREATE TABLE IF NOT EXISTS public.asistencias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL,
  fecha DATE NOT NULL,
  hora_programada_entrada TIME NULL,
  hora_programada_salida TIME NULL,
  tolerancia_minutos INTEGER NULL,
  hora_ingreso TIME NULL,
  hora_salida TIME NULL,
  minutos_tardanza INTEGER DEFAULT 0,
  horas_trabajadas DECIMAL(5,2) DEFAULT 0.00,
  estado VARCHAR(20) CHECK (estado IN ('presente', 'falta', 'tardanza', 'permiso', 'descanso', 'feriado', 'vacaciones', 'justificado')) NOT NULL DEFAULT 'presente',
  observacion VARCHAR(255) NULL,
  registrado_por_usuario_id INTEGER NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE,
  FOREIGN KEY (registrado_por_usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL,
  CONSTRAINT uk_asistencia_diaria UNIQUE (empleado_id, fecha)
);

CREATE TABLE IF NOT EXISTS public.tipo_permisos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.permisos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL,
  tipo_permiso VARCHAR(50) NOT NULL DEFAULT 'Personal',
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  hora_desde TIME NULL,
  hora_hasta TIME NULL,
  motivo TEXT NOT NULL,
  observaciones TEXT NULL,
  estado VARCHAR(20) CHECK (estado IN ('Solicitado', 'Aprobado', 'Rechazado')) DEFAULT 'Solicitado',
  archivo_sustento VARCHAR(255) NULL,
  archivo_sustento_nombre VARCHAR(200) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.tipo_documentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  descripcion TEXT NULL,
  es_obligatorio BOOLEAN DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS public.documentos_empleado (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL,
  tipo_documento_id INTEGER NOT NULL,
  nombre_archivo VARCHAR(255) NOT NULL,
  ruta_archivo VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NULL,
  observacion TEXT NULL,
  revisado_por INTEGER NULL,
  fecha_revision TIMESTAMP WITHOUT TIME ZONE NULL,
  estado VARCHAR(20) CHECK (estado IN ('pendiente', 'validado', 'rechazado')) DEFAULT 'pendiente',
  fecha_subida TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE,
  FOREIGN KEY (tipo_documento_id) REFERENCES tipo_documentos(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.plantillas_documentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(50) NOT NULL UNIQUE,
  titulo VARCHAR(150) NOT NULL,
  cuerpo_html TEXT NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.contratos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id INTEGER NOT NULL,
  codigo VARCHAR(40) NULL UNIQUE,
  tipo_contrato VARCHAR(80) NOT NULL,
  modalidad VARCHAR(80) NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NULL,
  remuneracion DECIMAL(10,2) NULL,
  moneda CHAR(3) NOT NULL DEFAULT 'PEN',
  horas_semanales DECIMAL(5,2) NULL,
  estado VARCHAR(20) CHECK (estado IN ('borrador','vigente','finalizado','cancelado')) NOT NULL DEFAULT 'borrador',
  observaciones TEXT NULL,
  documento_empleado_id INTEGER NULL,
  creado_por_usuario_id INTEGER NULL,
  actualizado_por_usuario_id INTEGER NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE RESTRICT,
  FOREIGN KEY (documento_empleado_id) REFERENCES documentos_empleado(id) ON DELETE SET NULL,
  FOREIGN KEY (creado_por_usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL,
  FOREIGN KEY (actualizado_por_usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.capacitaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(160) NOT NULL,
  categoria VARCHAR(100) NULL,
  descripcion TEXT NULL,
  modalidad VARCHAR(20) CHECK (modalidad IN ('presencial','virtual','hibrida')) NOT NULL DEFAULT 'presencial',
  proveedor VARCHAR(150) NULL,
  empresa_id INTEGER NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  hora_inicio TIME NULL,
  hora_fin TIME NULL,
  horas DECIMAL(7,2) NOT NULL,
  lugar VARCHAR(255) NULL,
  enlace VARCHAR(1000) NULL,
  cupo INTEGER NULL,
  obligatorio BOOLEAN NOT NULL DEFAULT FALSE,
  estado VARCHAR(20) CHECK (estado IN ('borrador','programada','en_curso','finalizada','cancelada')) NOT NULL DEFAULT 'borrador',
  creado_por_usuario_id INTEGER NULL,
  actualizado_por_usuario_id INTEGER NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (empresa_id) REFERENCES empresas(id) ON DELETE SET NULL,
  FOREIGN KEY (creado_por_usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL,
  FOREIGN KEY (actualizado_por_usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.capacitacion_participantes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capacitacion_id INTEGER NOT NULL,
  empleado_id INTEGER NOT NULL,
  estado VARCHAR(20) CHECK (estado IN ('inscrito','en_curso','aprobado','desaprobado','no_asistio','cancelado')) NOT NULL DEFAULT 'inscrito',
  asistencia_porcentaje DECIMAL(5,2) NULL,
  nota DECIMAL(5,2) NULL,
  fecha_inscripcion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  fecha_completado TIMESTAMP WITHOUT TIME ZONE NULL,
  observaciones TEXT NULL,
  certificado_documento_id INTEGER NULL,
  FOREIGN KEY (capacitacion_id) REFERENCES capacitaciones(id) ON DELETE CASCADE,
  FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE RESTRICT,
  FOREIGN KEY (certificado_documento_id) REFERENCES documentos_empleado(id) ON DELETE SET NULL,
  CONSTRAINT uk_capacitacion_empleado UNIQUE (capacitacion_id, empleado_id)
);

CREATE TABLE IF NOT EXISTS public.historial_cambios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NULL,
  tabla_afectada VARCHAR(60) NOT NULL,
  registro_id INTEGER NOT NULL,
  accion VARCHAR(20) CHECK (accion IN ('INSERT', 'UPDATE', 'DELETE', 'LOGIN', 'LOGIN_FALLIDO', 'DENEGADO', 'ERROR')) NOT NULL,
  datos_anteriores JSON NULL,
  datos_nuevos JSON NULL,
  ip_origen VARCHAR(45) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.subidas_pendientes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  empleado_id INTEGER NOT NULL REFERENCES public.empleados(id) ON DELETE CASCADE,
  tipo_documento_id INTEGER NULL REFERENCES public.tipo_documentos(id) ON DELETE SET NULL,
  categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('documento','permiso')),
  nombre_archivo VARCHAR(200) NOT NULL,
  ruta_archivo VARCHAR(100) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  tamano INTEGER NOT NULL CHECK (tamano BETWEEN 1 AND 5242880),
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '20 minutes'),
  consumido BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_subidas_pendientes_usuario_fecha
  ON public.subidas_pendientes(usuario_id,expires_at);

-- Índices adicionales del esquema
