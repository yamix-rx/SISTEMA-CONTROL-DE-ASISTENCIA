CREATE INDEX IF NOT EXISTS idx_cap_part_empleado ON public.capacitacion_participantes (empleado_id);
CREATE INDEX IF NOT EXISTS idx_cap_part_estado ON public.capacitacion_participantes (estado);

CREATE OR REPLACE FUNCTION public.sbss_touch_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
-- Asegurar search_path y restringir EXECUTE: evita avisos del auditor de seguridad.
ALTER FUNCTION public.sbss_touch_updated_at() SET search_path = '';
REVOKE EXECUTE ON FUNCTION public.sbss_touch_updated_at() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER trg_empleados_updated_at BEFORE UPDATE ON public.empleados
FOR EACH ROW EXECUTE FUNCTION public.sbss_touch_updated_at();
CREATE TRIGGER trg_asistencias_updated_at BEFORE UPDATE ON public.asistencias
FOR EACH ROW EXECUTE FUNCTION public.sbss_touch_updated_at();
CREATE TRIGGER trg_plantillas_documentos_updated_at BEFORE UPDATE ON public.plantillas_documentos
FOR EACH ROW EXECUTE FUNCTION public.sbss_touch_updated_at();
CREATE TRIGGER trg_contratos_updated_at BEFORE UPDATE ON public.contratos
FOR EACH ROW EXECUTE FUNCTION public.sbss_touch_updated_at();
CREATE TRIGGER trg_capacitaciones_updated_at BEFORE UPDATE ON public.capacitaciones
FOR EACH ROW EXECUTE FUNCTION public.sbss_touch_updated_at();

